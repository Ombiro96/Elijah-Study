export type SlideLayout =
  | "standard"
  | "mystery" // a question posed on-screen, deliberately left unanswered
  | "flashback" // a large "N Years Earlier..." transition card
  | "map" // a real, sourced historical map (see src/data/maps.ts)
  | "artifacts" // one or two real, sourced archaeological photos (see src/data/artifacts.ts)
  | "diagram" // a hand-drawn schematic of what the text states (see `diagramId`)
  | "compare" // two scripture passages set side by side
  | "parallels" // two figures compared line by line (see `parallels`)
  | "cliffhanger"; // fades to black, then teases the next week

export interface CompareBlock {
  leftLabel: string;
  leftRef: string;
  leftText: string;
  rightLabel: string;
  rightRef: string;
  rightText: string;
  /** The near-identical wording shared by both passages, surfaced on its own. */
  sharedPhrase: string;
  note?: string;
}

/** One point of contact between two figures, for a "parallels" slide. */
export interface ParallelRow {
  /** The thing being compared, shown between the two columns. */
  label: string;
  left: string;
  right: string;
}

export interface ParallelsBlock {
  leftName: string;
  leftSub?: string;
  rightName: string;
  rightSub?: string;
  rows: ParallelRow[];
  footnote?: string;
}

export interface Slide {
  id: string;
  week: 0 | 1 | 2 | 3 | 4;
  /**
   * Overrides the week label in the slide picker, for a session that sits
   * inside a week but is taught on its own night (e.g. 1 Kings 17).
   */
  deck?: string;
  kicker: string;
  title: string;
  bullets: string[];
  notes: string;
  scriptureRefs?: string[];
  layout?: SlideLayout;
  /** A short scripture quotation displayed large, e.g. for mystery/cliffhanger slides. */
  quote?: { text: string; ref: string };
  /** Big transition label for "flashback" slides, e.g. "800 Years Earlier...". */
  flashbackLabel?: string;
  /** References src/data/maps.ts for "map" slides. */
  mapId?: string;
  /** References src/data/artifacts.ts for "artifacts" slides — one or two side by side. */
  artifactIds?: string[];
  /** Which hand-drawn schematic to render for "diagram" slides. */
  diagramId?: "carmel-altars";
  compare?: CompareBlock;
  /** Two figures compared line by line, for "parallels" slides. */
  parallels?: ParallelsBlock;
  /** What to tease at the end of a "cliffhanger" slide, e.g. "Week 2 & 3 — The Prophet Appears". */
  nextLabel?: string;
  /** Visual weight hook for scenes that should read as heavier/darker. */
  tone?: "dark";
}

